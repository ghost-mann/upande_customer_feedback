function initialLang() {
  try {
    const saved = localStorage.getItem('portal_lang');
    if (saved && SUPPORTED.has(saved)) return saved;
  } catch (e) { /* ignore */ }
  const boot = String(window.lang || 'en').slice(0, 2).toLowerCase();
  return SUPPORTED.has(boot) ? boot : 'en';
}

// Reflect the language on <html> so the whole page flips to RTL for Arabic
// (text direction, scrollbars, form fields) and screen readers get the right lang.
function applyDir(lang) {
  try {
    const el = document.documentElement;
    el.setAttribute('dir', RTL.has(lang) ? 'rtl' : 'ltr');
    el.setAttribute('lang', lang);
  } catch (e) { /* ignore (SSR / no document) */ }
}

const _initialLang = initialLang();
applyDir(_initialLang);

export const useLangStore = create((set) => ({
  lang: _initialLang,
  setLang(lang) {
    if (!SUPPORTED.has(lang)) return;
    try { localStorage.setItem('portal_lang', lang); } catch (e) { /* ignore */ }
    applyDir(lang);
    set({ lang });
  },
}));

export function translate(lang, s) {
  if (lang === 'en' || s == null) return s;
  const table = DICT[lang];
  return (table && table[s]) || s;
}

// Hook: returns a `t` function bound to the current language. Subscribing to the
// store here makes every consumer re-render when the language changes.
export function useT() {
  const lang = useLangStore((s) => s.lang);
  return (s) => translate(lang, s);
}
